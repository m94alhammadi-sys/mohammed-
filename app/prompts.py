def _market_sessions(now: datetime) -> str:
    """حالة الجلسات الرئيسية بتوقيت المستخدم — يساعد الوكيل يعرف السوق مفتوح ولا لا."""
    weekday = now.weekday()          # 0 = الاثنين، 6 = الأحد
    hour = now.hour + now.minute / 60
    lines = []

    if weekday < 5:                  # الاثنين–الجمعة
        lines.append("🇦🇪 أسواق الإمارات (ADX/DFM): " + (
            "مفتوحة" if 10 <= hour < 15 else "مغلقة (تفتح 10:00 وتغلق 15:00 بتوقيت دبي)"))
    else:
        lines.append("🇦🇪 أسواق الإمارات: مغلقة (عطلة نهاية الأسبوع)")

    if weekday < 5:
        lines.append("🇺🇸 وول ستريت: " + (
            "مفتوحة" if 17.5 <= hour < 24 else "مغلقة (تفتح 17:30 بتوقيت دبي)"))
        lines.append("🇪🇺 أوروبا: " + ("مفتوحة" if 11 <= hour < 19.5 else "مغلقة"))
        lines.append("💱 الفوركس: مفتوح 24 ساعة (يغلق من جمعة مساءً حتى اثنين فجراً)")
    else:
        lines.append("🇺🇸🇪🇺 الأسواق العالمية: مغلقة (عطلة نهاية الأسبوع)")
        lines.append("💱 الفوركس: مغلق حتى فجر الاثنين")

    lines.append("₿ العملات الرقمية: مفتوحة دائماً")
    return "\n".join(lines)


def build_context(phone: str, user_name: str | None, watchlist: list[str], memory: dict) -> str:
    """سياق ديناميكي يُضاف بعد الـ system prompt الثابت (حتى لا يُبطل الكاش)."""
    now = datetime.now(ZoneInfo(settings.timezone))
    days_ar = ["الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت", "الأحد"]

    parts = [
        "# السياق الحالي",
        f"الوقت الآن: {days_ar[now.weekday()]} {now.strftime('%Y-%m-%d %H:%M')} بتوقيت {settings.timezone}",
        "",
        "## حالة الأسواق",
        _market_sessions(now),
    ]

    if user_name:
        parts += ["", f"## المستخدم\nالاسم: {user_name}"]

    if watchlist:
        parts += ["", "## قائمة متابعته", "، ".join(watchlist)]

    if memory:
        parts += ["", "## ما تعرفه عنه من محادثات سابقة"]
        parts += [f"- {k}: {v}" for k, v in memory.items()]

    return "\n".join(parts)


