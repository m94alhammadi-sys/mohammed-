def system_prompt() -> str:
    """نص النظام الثابت — يُبقى ثابتاً بايت ببايت ليستفيد من التخزين المؤقت."""
    return SYSTEM_PROMPT.format(disclaimer=DISCLAIMER)


def now_context(timezone: str) -> str:
    """الوقت والتاريخ يُمرَّران في رسالة المستخدم، لا في نص النظام، حفاظاً على الكاش."""
    try:
        tz = ZoneInfo(timezone)
    except Exception:
        tz = ZoneInfo("UTC")
    now = datetime.now(tz)
    return f"التاريخ والوقت الآن: {now.strftime('%Y-%m-%d %H:%M')} ({timezone})."


def build_user_turn(
    question: str,
    *,
    timezone: str,
    profile_context: str = "",
    market_block: str = "",
    watchlist: list[str] | None = None,
    holdings: list[dict] | None = None,
) -> str:
    """يجمع سؤال المستخدم مع سياقه الشخصي وبيانات السوق الحية."""
    parts = [now_context(timezone)]

    if profile_context:
        parts.append("ملف المستخدم:\n" + profile_context)

    if watchlist:
        parts.append("قائمة المتابعة: " + "، ".join(watchlist))

    if holdings:
        lines = []
        for h in holdings:
            avg = f"، متوسط السعر {h['avg_price']}" if h.get("avg_price") else ""
            note = f" ({h['note']})" if h.get("note") else ""
            lines.append(f"- {h['symbol']}: الكمية {h['quantity']}{avg}{note}")
        parts.append("محفظة المستخدم:\n" + "\n".join(lines))

    if market_block:
        parts.append(market_block)

    parts.append("سؤال المستخدم:\n" + question)
    return "\n\n".join(parts)


